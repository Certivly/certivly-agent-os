/**
 * ToolSchemaGenerator converts Tool specifications and JSON Schemas
 * into ambient TypeScript type declarations, function signatures, and docs.
 */

import type { WorkspaceTool } from '@agent-os/tools';

export interface GeneratedTypeDefinition {
  name: string;
  interfaceName: string;
  signature: string;
  declaration: string;
  jsDoc: string;
}

export class ToolSchemaGenerator {
  /**
   * Converts a JSON Schema object to a TypeScript type string.
   */
  public static jsonSchemaToType(schema: any, depth: number = 0): string {
    if (!schema) return 'any';

    if (schema.enum && Array.isArray(schema.enum)) {
      return schema.enum.map((e: any) => JSON.stringify(e)).join(' | ');
    }

    if (schema.type === 'string') return 'string';
    if (schema.type === 'number' || schema.type === 'integer') return 'number';
    if (schema.type === 'boolean') return 'boolean';
    if (schema.type === 'null') return 'null';

    if (schema.type === 'array') {
      const itemsType = schema.items ? this.jsonSchemaToType(schema.items, depth + 1) : 'any';
      return `${itemsType}[]`;
    }

    if (schema.type === 'object' || schema.properties) {
      if (!schema.properties || Object.keys(schema.properties).length === 0) {
        return 'Record<string, any>';
      }

      const indent = '  '.repeat(depth + 1);
      const closeIndent = '  '.repeat(depth);
      const required = new Set<string>(Array.isArray(schema.required) ? schema.required : []);

      const propDefs = Object.entries(schema.properties).map(([key, propSchema]: [string, any]) => {
        const isOptional = !required.has(key);
        const propType = this.jsonSchemaToType(propSchema, depth + 1);
        const doc = propSchema.description ? `${indent}/** ${propSchema.description} */\n` : '';
        const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
        return `${doc}${indent}${safeKey}${isOptional ? '?' : ''}: ${propType};`;
      });

      return `{\n${propDefs.join('\n')}\n${closeIndent}}`;
    }

    if (Array.isArray(schema.oneOf)) {
      return schema.oneOf.map((s: any) => this.jsonSchemaToType(s, depth)).join(' | ');
    }

    if (Array.isArray(schema.anyOf)) {
      return schema.anyOf.map((s: any) => this.jsonSchemaToType(s, depth)).join(' | ');
    }

    return 'any';
  }

  /**
   * Generates a TypeScript type definition for a single tool.
   */
  public static generateToolDeclaration(tool: WorkspaceTool): GeneratedTypeDefinition {
    const name = tool.spec.name;
    const pascalName = name
      .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
      .replace(/^[a-z]/, c => c.toUpperCase());
    const interfaceName = `${pascalName}Params`;

    const description = tool.spec.description || 'No description provided.';
    const paramsType = this.jsonSchemaToType(tool.spec.parameters, 0);

    const jsDoc = [
      '/**',
      ` * ${description.replace(/\n/g, '\n * ')}`,
      tool.spec.readOnly ? ' * @readonly This tool does not modify state.' : '',
      ' */',
    ]
      .filter(Boolean)
      .join('\n');

    let decl = `${jsDoc}\nexport interface ${interfaceName} ${paramsType}\n\n`;
    const signature = `${name}(args: ${interfaceName}): Promise<any>;`;

    return {
      name,
      interfaceName,
      signature,
      declaration: decl,
      jsDoc,
    };
  }

  /**
   * Generates a complete ambient TypeScript .d.ts file representing the entire catalog.
   */
  public static generateCatalogDts(tools: WorkspaceTool[]): string {
    const lines: string[] = [
      '// Generated by @agent-os/codemode ToolSchemaGenerator',
      '// Ambient declarations for tools and standard libraries available in CodeMode scripts',
      '',
      'declare namespace tools {',
    ];

    for (const tool of tools) {
      const def = this.generateToolDeclaration(tool);
      lines.push(`  /** ${tool.spec.description || tool.spec.name} */`);
      lines.push(`  function ${def.signature}`);
      lines.push('');
    }

    lines.push('}');
    lines.push('');
    lines.push('declare const $codemode: {');
    lines.push('  search(query: string, maxResults?: number): {');
    lines.push('    query: string;');
    lines.push('    totalMatches: number;');
    lines.push('    tools: Array<{ name: string; description: string; signature: string }>;');
    lines.push('  };');
    lines.push('  listTools(): Array<{ name: string; description: string; signature: string }>;');
    lines.push('};');
    lines.push('');
    lines.push('declare const stdlib: {');
    lines.push('  collections: typeof import("@agent-os/codemode").Collections;');
    lines.push('  strings: typeof import("@agent-os/codemode").Strings;');
    lines.push('  math: typeof import("@agent-os/codemode").MathUtils;');
    lines.push('  json: typeof import("@agent-os/codemode").JsonUtils;');
    lines.push('  promises: typeof import("@agent-os/codemode").PromiseUtils;');
    lines.push('  date: typeof import("@agent-os/codemode").DateUtils;');
    lines.push('  url: typeof import("@agent-os/codemode").UrlUtils;');
    lines.push('  value: typeof import("@agent-os/codemode").ValueUtils;');
    lines.push('};');

    return lines.join('\n');
  }
}
